use std::{
    fmt::Display,
    io::{self, stderr},
    process::ExitCode,
};

use clap::{Parser, Subcommand};
use crossterm::{
    execute,
    style::{Print, Stylize},
};

#[derive(Parser, Debug)]
#[command(author, version, about, long_about = None, styles=get_styles())]
struct Command {
    #[command(subcommand)]
    subcommand: SubCommand,
}

#[derive(Subcommand, Debug)]
enum SubCommand {
    /// Compile a local package and all of its dependencies
    Build {
        #[clap(flatten)]
        command: commands::build::Command,
    },

    /// Analyze the current package and report errors, but don't build object files
    Check {
        #[clap(flatten)]
        command: commands::check::Command,
    },

    /// Remove artifacts generated by maky in the past
    Clean {
        #[clap(flatten)]
        command: commands::clean::Command,
    },

    /// Initialize a new maky package directory
    Init {
        #[clap(flatten)]
        command: commands::init::Command,
    },

    /// Run a binary or example of the local package
    Run {
        #[clap(flatten)]
        command: commands::run::Command,
    },

    /// Run the tests
    Test {
        #[clap(flatten)]
        command: commands::test::Command,
    },
}

#[tokio::main]
async fn main() -> io::Result<ExitCode> {
    Ok(match execute_command().await {
        Ok(result) => result,
        Err(error) => {
            print_error(error)?;
            ExitCode::SUCCESS
        }
    })
}

async fn execute_command() -> anyhow::Result<ExitCode> {
    let command = Command::parse();

    match command.subcommand {
        SubCommand::Build { command } => command.execute().await?,
        SubCommand::Check { command } => command.execute().await?,
        SubCommand::Clean { command } => command.execute().await?,
        SubCommand::Init { command } => command.execute().await?,
        SubCommand::Run { command } => return Ok(command.execute().await?),
        SubCommand::Test { command } => return Ok(command.execute().await?),
    }

    return Ok(ExitCode::SUCCESS);
}

fn print_error<T: Display>(error: T) -> io::Result<()> {
    execute!(
        stderr(),
        Print("error".dark_red().bold()),
        Print(": ".bold()),
        Print(error.to_string().reset()),
        Print("\n"),
    )
}

fn print_warning<T: Display>(warning: T) -> io::Result<()> {
    execute!(
        stderr(),
        Print("warning".yellow().bold()),
        Print(": ".bold()),
        Print(warning.to_string().reset()),
        Print("\n"),
    )
}

fn get_styles() -> clap::builder::Styles {
    clap::builder::Styles::styled()
        .usage(clap::builder::styling::Style::new().bold().fg_color(Some(
            clap::builder::styling::Color::Ansi(clap::builder::styling::AnsiColor::Green),
        )))
        .header(clap::builder::styling::Style::new().bold().fg_color(Some(
            clap::builder::styling::Color::Ansi(clap::builder::styling::AnsiColor::Green),
        )))
        .literal(clap::builder::styling::Style::new().bold().fg_color(Some(
            clap::builder::styling::Color::Ansi(clap::builder::styling::AnsiColor::Cyan),
        )))
        .invalid(clap::builder::styling::Style::new().bold().fg_color(Some(
            clap::builder::styling::Color::Ansi(clap::builder::styling::AnsiColor::Red),
        )))
        .error(clap::builder::styling::Style::new().bold().fg_color(Some(
            clap::builder::styling::Color::Ansi(clap::builder::styling::AnsiColor::Red),
        )))
        .valid(
            clap::builder::styling::Style::new()
                .bold()
                .underline()
                .fg_color(Some(clap::builder::styling::Color::Ansi(
                    clap::builder::styling::AnsiColor::Cyan,
                ))),
        )
        .placeholder(clap::builder::styling::Style::new().fg_color(Some(
            clap::builder::styling::Color::Ansi(clap::builder::styling::AnsiColor::Cyan),
        )))
}
